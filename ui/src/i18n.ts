function chineseTranslation(source: string): string | undefined {
  if (zh[source]) return zh[source];
  const missingQuote = source.match(/^Missing closing (.+) quote\.$/);
  const configValue = source.match(/^(\S+) requires a following configuration path\.$/);
  const configEquals = source.match(/^(\S+) requires a configuration path after “=”\.$/);
  const duplicateKey = source.match(/^Duplicate environment key: (.+)$/);
  const nullValue = source.match(/^Environment value for (.+) contains a null character\.$/);
  const failedProgramList = source.match(/^Could not stop: (.+)\.$/);
  const failedProgramRemainder = source.match(
    /^Could not stop (.+) and (\d+) other managed programs?\.$/,
  );
  if (missingQuote) return `缺少结束符 ${missingQuote[1]}`;
  if (configValue) return `${configValue[1]} 后需要配置路径`;
  if (configEquals) return `${configEquals[1]} 的“=”后需要配置路径`;
  if (duplicateKey) return `环境变量名称重复：${duplicateKey[1]}`;
  if (nullValue) return `${nullValue[1]} 的环境变量值包含空字符`;
  if (failedProgramList) return `无法停止：${failedProgramList[1]}。`;
  if (failedProgramRemainder) {
    return `无法停止 ${failedProgramRemainder[1]}，以及另外 ${failedProgramRemainder[2]} 个托管程序。`;
  }
  return undefined;
}

export function hasChineseTranslation(source: string): boolean {
  return chineseTranslation(source) !== undefined || /[\u3400-\u9fff]/u.test(source);
}

export const t = derived(uiLanguage, (language) => (source: string): string => {
  const result = language === 'zh-CN' ? chineseTranslation(source) ?? source : source;
  return result.replace(/[。.]+$/u, '');
});

export function translate(source: string): string {
  return get(t)(source);
}

export function setLanguage(language: UiLanguage): void {
  uiLanguage.set(language);
  document.documentElement.lang = language;
  try {
    localStorage.setItem(STORAGE_KEY, language);
  } catch {
    // The selection remains active for this session.
  }
}

